"""Compiles the feature spec into dialect-correct SQL.

The compiler exists so that the SQL in `sql/` is a build artifact with a
single source of truth, regenerated by `make sql` and diffed by CI, rather
than four hand-maintained copies that drift. Dialect differences are confined
to three expressions: subtracting days from a timestamp, the admissibility
predicate placement, and nothing else, which is itself a point the README
makes: the point-in-time contract is two comparisons, portable everywhere,
and the reason pipelines ship without it is not syntax.

Times appear twice in the schema on purpose. Predicates and window bounds use
the TIMESTAMP columns, because that is what warehouse SQL really joins on.
The one arithmetic feature (days since last activity) reads the float day
columns, so that every dialect and both engines produce bit-identical values
instead of values that differ by a second-truncation.
"""

from __future__ import annotations

from ..features.spec import FEATURES, FeatureSpec, visibility_predicate_text

DIALECTS = ("duckdb", "spark", "snowflake", "bigquery")


def _ts_sub(dialect: str, ts: str, days: int) -> str:
    if dialect in ("duckdb", "spark"):
        return f"{ts} - INTERVAL {days} DAY"
    if dialect == "snowflake":
        return f"DATEADD(DAY, -{days}, {ts})"
    if dialect == "bigquery":
        return f"TIMESTAMP_SUB({ts}, INTERVAL {days} DAY)"
    raise ValueError(f"unknown dialect: {dialect!r}")


def _window_ctes(dialect: str) -> tuple[list[str], dict[str, tuple[str, str]]]:
    """One CTE per (event_type, window) pair; returns (cte_sql, column_home)."""
    groups: dict[tuple[str, int], list[FeatureSpec]] = {}
    for f in FEATURES:
        if f.kind in ("window_count", "window_sum", "window_max"):
            groups.setdefault((f.event_type, f.window_days), []).append(f)

    ctes: list[str] = []
    home: dict[str, tuple[str, str]] = {}
    for (event_type, days), specs in groups.items():
        alias = f"{event_type}_window_{days}d"
        cols = []
        for f in specs:
            agg = {"window_count": "COUNT(*)", "window_sum": "SUM(value)", "window_max": "MAX(value)"}[f.kind]
            cols.append(f"        {agg} AS {f.name}")
            home[f.name] = (alias, f.name)
        lower = _ts_sub(dialect, "prediction_time", days)
        ctes.append(
            f"{alias} AS (\n"
            f"    SELECT\n"
            f"        entity_id,\n" + ",\n".join(cols) + "\n"
            f"    FROM visible\n"
            f"    WHERE event_type = '{event_type}'\n"
            f"      AND fact_time > {lower}\n"
            f"      AND fact_time <= prediction_time\n"
            f"    GROUP BY entity_id\n"
            f")"
        )
    return ctes, home


def _latest_ctes() -> tuple[list[str], dict[str, tuple[str, str]]]:
    ctes: list[str] = []
    home: dict[str, tuple[str, str]] = {}
    for f in FEATURES:
        if f.kind == "days_since_last":
            alias = f"last_{f.event_type}"
            ctes.append(
                f"{alias} AS (\n"
                f"    SELECT\n"
                f"        entity_id,\n"
                f"        prediction_days - MAX(fact_days) AS {f.name}\n"
                f"    FROM visible\n"
                f"    WHERE event_type = '{f.event_type}'\n"
                f"    GROUP BY entity_id, prediction_days\n"
                f")"
            )
            home[f.name] = (alias, f.name)
        elif f.kind in ("last_value", "last_status_eq"):
            alias = f"latest_{f.event_type}"
            if f.kind == "last_value":
                expr = f"value AS {f.name}"
            else:
                expr = f"CASE WHEN status = '{f.status_literal}' THEN 1.0 ELSE 0.0 END AS {f.name}"
            ctes.append(
                f"{alias} AS (\n"
                f"    SELECT entity_id, {expr}\n"
                f"    FROM (\n"
                f"        SELECT\n"
                f"            entity_id,\n"
                f"            value,\n"
                f"            status,\n"
                f"            ROW_NUMBER() OVER (\n"
                f"                PARTITION BY entity_id\n"
                f"                ORDER BY fact_time DESC, arrival_time DESC, event_id DESC\n"
                f"            ) AS rn\n"
                f"        FROM visible\n"
                f"        WHERE event_type = '{f.event_type}'\n"
                f"    ) ranked\n"
                f"    WHERE rn = 1\n"
                f")"
            )
            home[f.name] = (alias, f.name)
    return ctes, home


def emit_feature_sql(dialect: str, policy: str) -> str:
    """The full feature build for one dialect under one visibility policy."""
    if dialect not in DIALECTS:
        raise ValueError(f"unknown dialect: {dialect!r}")

    predicate = visibility_predicate_text(policy)
    join_tail = f"\n     AND {predicate}" if predicate else ""

    header = (
        f"-- Feature build, {dialect} dialect, visibility policy: {policy}.\n"
        f"-- Generated by tools/emit_sql.py from the spec in features/spec.py.\n"
        f"-- Edit the spec, not this file; `make sql` regenerates and CI diffs.\n"
        f"-- Tables resolve in the session's default schema or dataset.\n"
    )
    if policy == "latest":
        header += (
            "-- WARNING: this join admits every event the table holds, including\n"
            "-- facts recorded after prediction time. It exists as the measured\n"
            "-- counterexample, not as something to ship.\n"
        )
    elif policy == "fact_only":
        header += (
            "-- WARNING: fact_time alone does not establish that a value was\n"
            "-- knowable. A fact can be true before prediction time and arrive\n"
            "-- after it. This is the version that passes code review and leaks.\n"
        )

    window_ctes, window_home = _window_ctes(dialect)
    latest_ctes, latest_home = _latest_ctes()
    home = {**window_home, **latest_home}

    visible = (
        "visible AS (\n"
        "    SELECT\n"
        "        p.entity_id,\n"
        "        p.prediction_time,\n"
        "        p.prediction_days,\n"
        "        e.event_id,\n"
        "        e.event_type,\n"
        "        e.fact_time,\n"
        "        e.arrival_time,\n"
        "        e.fact_days,\n"
        "        e.value,\n"
        "        e.status\n"
        "    FROM predictions AS p\n"
        "    JOIN events AS e\n"
        f"      ON e.entity_id = p.entity_id{join_tail}\n"
        ")"
    )

    select_cols = ["    p.entity_id"]
    joins = []
    seen_aliases = []
    for f in FEATURES:
        alias, col = home[f.name]
        if f.kind in ("window_count", "window_sum"):
            zero = "0" if f.kind == "window_count" else "0.0"
            select_cols.append(f"    COALESCE({alias}.{col}, {zero}) AS {f.name}")
        elif f.kind == "last_status_eq":
            select_cols.append(f"    COALESCE({alias}.{col}, 0.0) AS {f.name}")
        else:
            select_cols.append(f"    {alias}.{col} AS {f.name}")
        if alias not in seen_aliases:
            joins.append(f"LEFT JOIN {alias}\n    ON {alias}.entity_id = p.entity_id")
            seen_aliases.append(alias)

    body = (
        "WITH " + ",\n".join([visible, *window_ctes, *latest_ctes]) + "\n"
        "SELECT\n" + ",\n".join(select_cols) + "\n"
        "FROM predictions AS p\n" + "\n".join(joins) + "\n"
        "ORDER BY p.entity_id\n"
    )
    return header + body
